'use strict';

// Reason: imported map coordinates must work in real matches, including every
// configured supply chest and refill. Pure metadata checks cannot catch a wrong
// world offset, a glass cage placed in terrain, or missed delayed cleanup.
// Protocol clients check server state only; this script does not check rendering.
// Run against an isolated 1.21.1 server with OP MapCheckA/B/C, refill=15 seconds,
// shrink start=180 seconds, and configVersion=17. Never starts or stops a server.
// SKYWARS_TEST_NODE_MODULES=... SKYWARS_TEST_RUN_DIR=... SKYWARS_TEST_PORT=25567 \
//   node tools/skywars_imported_maps_regression.cjs
const fs = require('node:fs');
const path = require('node:path');
const moduleRoot = path.resolve(process.env.SKYWARS_TEST_NODE_MODULES || '/tmp/pvp-protocol-check/node_modules');
const mineflayer = require(path.join(moduleRoot, 'mineflayer'));
const { Vec3 } = require(path.join(moduleRoot, 'vec3'));
if (!process.env.SKYWARS_TEST_RUN_DIR) throw new Error('Set SKYWARS_TEST_RUN_DIR to the isolated server directory.');
const runDir = path.resolve(process.env.SKYWARS_TEST_RUN_DIR);
const port = Number(process.env.SKYWARS_TEST_PORT || 25567);
if (!Number.isInteger(port) || port < 1 || port > 65535 || port === 25565) {
  throw new Error('Use an isolated test port; port 25565 is forbidden.');
}
const properties = fs.readFileSync(path.join(runDir, 'server.properties'), 'utf8');
if (Number(properties.match(/^server-port=(\d+)\s*$/m)?.[1]) !== port) {
  throw new Error('SKYWARS_TEST_RUN_DIR server port does not match SKYWARS_TEST_PORT.');
}
const sourceDir = path.join(process.cwd(), 'src/main/resources/maps/skywars');
const extrasOnly = process.env.SKYWARS_TEST_ROUNDS === 'extras';
const metadata = Object.fromEntries(['forest', 'unresting_desert'].map(id => {
  const map = JSON.parse(fs.readFileSync(path.join(sourceDir, id, 'metadata.json'), 'utf8'));
  if (map.id !== id || map.spawns.length < 3 || map.chests.length !== 44 || !map.name || !map.author) {
    throw new Error(`Unexpected bundled map metadata: ${id}`);
  }
  return [id, map];
}));
const mapsConfig = path.join(runDir, 'config/pvp/skywars/maps.json');
const originalConfig = fs.existsSync(mapsConfig) ? fs.readFileSync(mapsConfig) : null;
const logfile = path.join(runDir, 'skywars-imported-maps-results.jsonl');
const ids = ['A', 'B', 'C'], bots = {}, chats = [], assertions = [];
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const stringify = value => JSON.stringify(value, (_, v) => typeof v === 'bigint' ? v.toString() : v);
let round = 'bootstrap', serial = 0, closing = false, fatal;
let selecting = false;
const selected = new Set();
const forcedChunks = new Set();
function emit(event, detail = {}) {
  const row = stringify({ time: new Date().toISOString(), round, event, ...detail });
  fs.appendFileSync(logfile, row + '\n');
  process.stdout.write(row + '\n');
}
function check(name, pass, actual, expected) {
  const result = { name, pass: !!pass, actual, expected };
  assertions.push(result);
  emit('assertion', result);
  if (!pass) throw new Error(`Assertion failed: ${name}`);
}
async function until(predicate, label, timeout = 25000) {
  const deadline = Date.now() + timeout;
  while (!predicate()) {
    if (fatal) throw fatal;
    if (Date.now() > deadline) throw new Error(`Timeout: ${label}`);
    await sleep(20);
  }
}
function snapshot(id) {
  const bot = bots[id];
  return { id, world: bot.testWorldName, position: bot.entity?.position,
    mode: bot.game?.gameMode, health: bot.health };
}
function connect(id) {
  const bot = bots[id] = mineflayer.createBot({ host: '127.0.0.1', port,
    username: `MapCheck${id}`, version: '1.21.1', auth: 'offline',
    physicsEnabled: false, hideErrors: true });
  let authoritative;
  const write = bot._client.write.bind(bot._client);
  bot._client.write = (name, packet) => {
    // The probes only move via /tp. Drop stale movement generated by a delayed
    // Mineflayer spawn/respawn reply instead of reverting a server teleport.
    if (authoritative && (name === 'position' || name === 'position_look')) {
      if (bot.entity) bot.entity.position.set(authoritative.x, authoritative.y, authoritative.z);
      return name === 'position_look'
        ? write('look', { yaw: packet.yaw, pitch: packet.pitch, onGround: true })
        : write('flying', { onGround: true });
    }
    return write(name, packet);
  };
  bot._client.prependListener('position', packet => {
    const prior = authoritative || bot.entity?.position || new Vec3(0, 0, 0);
    const relative = axis => typeof packet.flags === 'object'
      ? packet.flags[axis] : !!(packet.flags & { x: 1, y: 2, z: 4 }[axis]);
    authoritative = new Vec3((relative('x') ? prior.x : 0) + packet.x,
      (relative('y') ? prior.y : 0) + packet.y, (relative('z') ? prior.z : 0) + packet.z);
    emit('teleport', { id, position: authoritative });
  });
  for (const event of ['login', 'respawn']) bot._client.prependListener(event, packet => {
    const state = packet.worldState || packet;
    bot.testWorldName = state.name ?? state.worldName ?? packet.worldName;
    emit('world', { id, world: bot.testWorldName });
  });
  bot.on('spawn', () => { bot.physicsEnabled = false; emit('spawn', snapshot(id)); });
  bot.on('messagestr', (text, position) => {
    const message = text.replace(/§./g, '');
    chats.push({ id, message, position });
    if (position !== 'game_info') emit('chat', { id, message });
  });
  bot.on('windowOpen', async window => {
    emit('window', { id, title: window.title });
    if (!selecting || !JSON.stringify(window.title).includes('选择空岛战争职业')) return;
    try {
      await bot.clickWindow(0, 0, 0);
      selected.add(id);
      emit('professionSelected', { id, slot: 0 });
    } catch (error) { fatal = error; emit('error', { id, message: error.stack }); }
  });
  // These are headless acknowledgements used to enter the gun map round. They
  // do not claim the resource pack was rendered, played, or visually inspected.
  bot._client.on('add_resource_pack', packet => {
    emit('headlessPackAcknowledgement', { id, uuid: packet.uuid, rendered: false });
    for (const result of [3, 4, 0]) bot._client.write('resource_pack_receive', { uuid: packet.uuid, result });
  });
  bot.on('error', error => { fatal = error; emit('error', { id, message: error.stack }); });
  bot.on('kicked', reason => {
    if (!closing) { fatal = new Error(`${bot.username} kicked: ${stringify(reason)}`); emit('error', { id, reason }); }
  });
}
async function cmd(command, delay = 35, id = 'A') {
  if (fatal) throw fatal;
  if (command.length > 256) throw new Error('Test command exceeds vanilla chat limit.');
  bots[id].chat(command);
  await sleep(delay);
}
function marker() { return `SWMAP_${String(++serial).padStart(5, '0')}`; }
function saw(mark, from) { return chats.slice(from).some(c => c.id === 'A' && c.message.includes(mark)); }
function pos(value) { return `${value.x} ${value.y} ${value.z}`; }
function add(a, b) { return { x: a.x + b.x, y: a.y + b.y, z: a.z + b.z }; }
function cell(p) { return { x: Math.floor(p.x), y: Math.floor(p.y), z: Math.floor(p.z) }; }
async function confirmCommands(cases, label) {
  const begin = chats.length;
  const probes = cases.map((item, index) => ({ ...item, index, mark: marker() }));
  for (const probe of probes) {
    await cmd(`/execute in pvp:arena ${probe.condition} run say ${probe.mark}`);
  }
  // Server ticks batch commands; wait for all result messages before asserting.
  const deadline = Date.now() + 3000;
  while (!probes.every(p => saw(p.mark, begin)) && Date.now() < deadline) await sleep(20);
  for (const probe of probes) {
    check(`${label} #${probe.index + 1}`, saw(probe.mark, begin), probe.detail ?? probe.condition, 'condition succeeds');
  }
}
function configure(id, enabled = true) {
  fs.mkdirSync(path.dirname(mapsConfig), { recursive: true });
  fs.writeFileSync(mapsConfig, JSON.stringify({ enabled, forcedMap: id || '', generatedWeight: 0,
    maps: { forest: 1, unresting_desert: 1 } }, null, 2) + '\n');
  emit('mapConfig', { enabled, forcedMap: id || '' });
}
function inferCenter(map, cageFeet) {
  const first = cageFeet.A;
  const candidates = map.spawns.map(spawn => ({ x: first.x - spawn.x,
    y: first.y - 10 - spawn.y, z: first.z - spawn.z })).filter(center => {
    if (center.y !== 101 || (center.x - center.z) % 384 !== 0) return false;
    return ids.every(id => map.spawns.some(spawn => {
      const expected = add(center, spawn), actual = cageFeet[id];
      return expected.x === actual.x && expected.y + 10 === actual.y && expected.z === actual.z;
    }));
  });
  const unique = [...new Map(candidates.map(c => [pos(c), c])).values()];
  check('one metadata offset matches all real spawn cages', unique.length === 1, unique, 'one center');
  return unique[0];
}
async function beginRound(mapId, gun = false, enabled = true) {
  round = enabled ? `${mapId}:${gun ? 'guns' : 'normal'}` : 'generated:fallback';
  configure(mapId, enabled);
  selected.clear();
  selecting = !gun;
  const begin = chats.length;
  for (const id of ids) {
    await cmd(`/pvp join ${gun ? 'skywarsguns' : 'skywars'}`, 180, id);
    if (gun && chats.slice(begin).some(c => c.id === id && c.message.includes('请接受 MyGO 资源包'))) {
      await until(() => chats.slice(begin).some(c => c.id === id && c.message.includes('资源包加载成功')),
        `${id} gun resource pack handshake`);
      // Loading the resource pack deliberately does not queue the player;
      // follow the server prompt and explicitly join again after it succeeds.
      await cmd('/pvp join skywarsguns', 180, id);
    }
  }
  await cmd('/pvp start', 50);
  await until(() => ids.every(id => bots[id].testWorldName === 'pvp:arena')
    && chats.slice(begin).some(c => c.id === 'A' && c.message.includes('空岛') && c.message.includes('开始！')),
  'map built and players entered countdown', 45000);
  const map = enabled ? metadata[mapId] : null;
  const opening = chats.slice(begin).filter(c => c.id === 'A').map(c => c.message).join('\n');
  if (map) {
    check('opening announces imported map name', opening.includes(map.name), opening, map.name);
    await until(() => chats.slice(begin).some(c => c.id === 'A' && c.message.includes(map.author)), 'author attribution');
    check('opening credits map author', chats.slice(begin).some(c => c.id === 'A'
      && c.message.includes(map.author)), map.author);
  } else {
    check('disabled map pool opens generated map', !Object.values(metadata).some(m => opening.includes(m.name)), opening);
  }
  const cageFeet = Object.fromEntries(ids.map(id => [id, cell(bots[id].entity.position)]));
  check('players have distinct spawn cages', new Set(ids.map(id => pos(cageFeet[id]))).size === ids.length, cageFeet);
  const center = map ? inferCenter(map, cageFeet) : null;
  const grounds = ids.map(id => ({ id, x: cageFeet[id].x, y: cageFeet[id].y - 10, z: cageFeet[id].z }));
  for (const id of ids) {
    const feet = cageFeet[id];
    check(`${id} player centered inside cage`, Math.abs(bots[id].entity.position.x - feet.x - 0.5) < 0.01
      && Math.abs(bots[id].entity.position.z - feet.z - 0.5) < 0.01, snapshot(id));
  }
  await confirmCommands(ids.flatMap(id => {
    const feet = cageFeet[id];
    const floor = { x: feet.x, y: feet.y - 11, z: feet.z };
    return [{ condition: `if block ${feet.x} ${feet.y - 1} ${feet.z} minecraft:glass`, detail: `${id} cage floor` },
      { condition: `unless block ${pos(floor)} minecraft:air`, detail: `${id} safe ground ten blocks below cage` }];
  }), 'countdown cage and ground');
  if (!gun) {
    await until(() => ids.every(id => selected.has(id)), 'all profession GUI choices');
    check('profession GUI works for all players', selected.size === ids.length, [...selected]);
  }
  await until(() => chats.slice(begin).some(c => c.id === 'A' && c.message.includes('战斗开始！')), 'active battle', 20000);
  selecting = false;
  await confirmCommands(ids.map(id => ({ condition: `if block ${cageFeet[id].x} ${cageFeet[id].y - 1} ${cageFeet[id].z} minecraft:air`,
    detail: `${id} cage floor removed` })), 'active cages removed');
  for (const ground of grounds) await cmd(`/execute in pvp:arena run tp MapCheck${ground.id} ${ground.x + 0.5} ${ground.y} ${ground.z + 0.5}`);
  const chests = map ? map.chests.map(chest => ({ ...add(center, chest), tier: chest.tier })) : [];
  // Include a block beyond the source map bounds, where a player may build a
  // bridge; cleanup must reclaim the allocated region, not only original art.
  const markerPos = center ? add(center, { x: map.maxRadius + 12, y: 70, z: 0 })
    : { x: grounds[0].x, y: grounds[0].y + 50, z: grounds[0].z };
  await cmd(`/execute in pvp:arena run setblock ${pos(markerPos)} minecraft:gold_block`);
  return { map, center, cageFeet, grounds, chests, markerPos, begin };
}
async function checkFilled(chests, label) {
  await confirmCommands(chests.map(chest => ({
    condition: `if data block ${pos(chest)} Items[0] unless data block ${pos(chest)} LootTable`,
    detail: chest
  })), label);
}
async function refillRound(context) {
  await checkFilled(context.chests, 'initial supply present without vanilla LootTable');
  check('first fill checked before refill', !chats.slice(context.begin).some(c => c.id === 'A'
    && c.message.includes('所有箱子物资已刷新')), 'refill not yet announced');
  for (const chest of context.chests) await cmd(`/execute in pvp:arena run data modify block ${pos(chest)} Items set value []`);
  await confirmCommands(context.chests.map(chest => ({ condition: `unless data block ${pos(chest)} Items[0]`, detail: chest })),
    'chests explicitly emptied before refill');
  await until(() => chats.slice(context.begin).some(c => c.id === 'A' && c.message.includes('所有箱子物资已刷新')),
    'one server-driven refill', 30000);
  await checkFilled(context.chests, 'all configured chests refilled without vanilla LootTable');
}
async function cleanupRound(context) {
  for (const id of ids) await cmd('/hub', 180, id);
  await until(() => ids.every(id => bots[id].testWorldName !== 'pvp:arena'), 'all players leave arena');
  await sleep(8000);
  const probes = [...context.chests, ...context.grounds.map(g => ({ x: g.x, y: g.y - 1, z: g.z })), context.markerPos];
  // Reopen the relevant chunks after delayed cleanup so persisted leftovers
  // cannot be hidden by unloading when the last participant leaves.
  const chunks = [...new Set(probes.map(p => `${Math.floor(p.x / 16) * 16} ${Math.floor(p.z / 16) * 16}`))];
  for (const chunk of chunks) { await cmd(`/execute in pvp:arena run forceload add ${chunk}`); forcedChunks.add(chunk); }
  await sleep(300);
  await confirmCommands(probes.map(p => ({ condition: `if block ${pos(p)} minecraft:air`, detail: p })),
    'delayed cleanup removes chests, spawn floors and player block');
  for (const chunk of chunks) { await cmd(`/execute in pvp:arena run forceload remove ${chunk}`); forcedChunks.delete(chunk); }
}
(async () => {
  try {
    emit('start', { port, runDir, sourceDir, headless: true });
    for (const id of ids) connect(id);
    await until(() => ids.every(id => bots[id].entity), 'all test clients online');
    for (const id of ids) await cmd('/hub', 180, id);
    for (const id of extrasOnly ? [] : ['forest', 'unresting_desert']) {
      const context = await beginRound(id);
      await refillRound(context);
      await cleanupRound(context);
    }
    const gun = await beginRound('forest', true);
    await checkFilled(gun.chests, 'gun map fills all 44 chests');
    await confirmCommands(gun.chests.map(chest => ({
      condition: `if data block ${pos(chest)} Items[].components."minecraft:custom_data"."pvp.skywars_gun"`, detail: chest
    })), 'gun map chests contain tagged MyGO weapons');
    await cleanupRound(gun);
    const generated = await beginRound('', false, false);
    await cleanupRound(generated);
    emit('complete', { assertions: assertions.length, passed: assertions.filter(a => a.pass).length });
  } catch (error) {
    emit('failure', { message: error.stack });
    process.exitCode = 1;
  } finally {
    // Restore only the test file changed here; leave server lifecycle to caller.
    if (originalConfig === null) {
      if (fs.existsSync(mapsConfig)) fs.unlinkSync(mapsConfig);
    } else fs.writeFileSync(mapsConfig, originalConfig);
    for (const chunk of forcedChunks) {
      if (bots.A?._client?.state === 'play') bots.A.chat(`/execute in pvp:arena run forceload remove ${chunk}`);
    }
    closing = true;
    for (const bot of Object.values(bots)) bot.quit();
    setTimeout(() => process.exit(process.exitCode || 0), 300);
  }
})();
